'use client';

import Link from 'next/link';
import { usePathname } from 'next/navigation';
import '@/styles/admin-sidebar.css';
import Image from 'next/image';


interface AdminSidebarProps {
  isOpen: boolean;
  onClose: () => void;
  logo?: string;
  logoAlt?: string;
}

const navigationItems = [
  { name: 'Dashboard', href: '/admin', icon: HomeIcon },
  { name: 'Orders', href: '/admin/orders', icon: FolderIcon },
  { name: 'Products', href: '/admin/products', icon: TagIcon },
  { name: 'Statistics', href: '/admin/statistics', icon: ChartIcon },
  { name: 'Customers', href: '/admin/customers', icon: UsersIcon },
];

const bottomItems = [
  { name: 'Help', href: '/admin/help', icon: HelpIcon },
  { name: 'Settings', href: '/admin/settings', icon: SettingsIcon },
];

export default function AdminSidebar({ isOpen, onClose, logo = "/assets/logo.png",
  logoAlt = "Logo", }: AdminSidebarProps) {
  const pathname = usePathname();

  return (
    <>
      {/* Mobile overlay */}
      {isOpen && (
        <div
          className="sidebar-overlay"
          onClick={onClose}
        />
      )}

      {/* Sidebar */}
      <aside
        className={`sidebar-container ${isOpen ? 'open' : 'closed'}`}
      >
        <div className="flex h-full flex-col">
          {/* Logo */}
          <Link href="/" className="sidebar-logo">
            <Image
              src={logo}
              alt={logoAlt}
              width={140}
              height={40}
              className="h-8 sm:h-10 w-auto"
            />
          </Link>

          {/* Navigation */}
          <nav className="sidebar-nav">
            {navigationItems.map((item) => {
              const isActive = pathname === item.href;
              return (
                <Link
                  key={item.name}
                  href={item.href}
                  onClick={() => {
                    if (window.innerWidth < 1024) {
                      onClose();
                    }
                  }}
                  className={`sidebar-nav-item ${isActive ? 'active' : 'inactive'}`}
                >
                  <item.icon className="sidebar-icon" />
                  {item.name}
                </Link>
              );
            })}
          </nav>

          {/* Bottom  */}
          <div className="sidebar-bottom">
            {bottomItems.map((item) => {
              const isActive = pathname === item.href;
              return (
                <Link
                  key={item.name}
                  href={item.href}
                  onClick={() => {
                    if (window.innerWidth < 1024) {
                      onClose();
                    }
                  }}
                  className={`sidebar-nav-item ${isActive ? 'active' : 'inactive'}`}
                >
                  <item.icon className="sidebar-icon" />
                  {item.name}
                </Link>
              );
            })}
          </div>
        </div>
      </aside>
    </>
  );
}

